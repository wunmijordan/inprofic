const {test,expect}=require('@playwright/test');
test('daily expense requests can be edited, removed and approved from the purchasing workspace',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('inprofic:essential-privacy-notice:v1','dismissed'));
 await page.goto('/accounts/login/ui-fixture/admin/');
 await page.goto('/procurement/');
 await expect(page.getByRole('link',{name:'+ Record purchase',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'+ Expense request',exact:true})).toBeVisible();
 await page.goto('/expenses/requests/add/');
 const first=page.locator('[data-expense-request-line]').first();
 await first.locator('input[name$="-description"]').fill('Transport for collections');
 await first.locator('input[name$="-amount"]').fill('100');
 await page.getByRole('button',{name:'+ Add expense',exact:true}).click();
 const initialSecond=page.locator('[data-expense-request-line]').nth(1);
 await initialSecond.locator('input[name$="-description"]').fill('Repairs');
 await initialSecond.locator('input[name$="-amount"]').fill('200');
 await page.getByRole('button',{name:'Save request',exact:true}).click();
 await expect(page).toHaveURL(/\/expenses\/requests\/\d+\/$/);
 await expect(page.getByRole('button',{name:'Approve expenses',exact:true})).toBeVisible();
 await page.locator('[data-expense-request-line]').first().locator('input[name$="-amount"]').fill('150');
 await page.locator('[data-expense-request-line]').first().locator('textarea[name$="-approval_reason"]').fill('Updated transport quote');
 const removedExisting=page.locator('[data-expense-request-line]').nth(1);
 await removedExisting.getByRole('button',{name:'Remove item',exact:true}).click();
 await expect(removedExisting.locator('[data-expense-request-fields]')).not.toBeVisible();
 await removedExisting.locator('textarea[name$="-approval_reason"]').fill('Repair postponed');
 await page.getByRole('button',{name:'+ Add expense',exact:true}).click();
 const second=page.locator('[data-expense-request-line]').nth(2);
 await second.locator('input[name$="-description"]').fill('Cancelled item');
 await second.locator('input[name$="-amount"]').fill('50');
 await second.getByRole('button',{name:'Remove item',exact:true}).click();
 await expect(second).not.toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:'/tmp/inprofic-expense-request-mobile.png'});
 await page.getByRole('button',{name:'Approve expenses',exact:true}).click();
 await expect(page.getByRole('button',{name:'Approve expenses',exact:true})).toHaveCount(0);
 await expect(page.getByRole('heading',{level:1})).toContainText('General-use expense request');
 await expect(page.locator('[data-expense-request-line] input[name$="-amount"]')).toHaveValue('150.00');
 await page.goto('/procurement/');
 await expect(page.locator('tr').filter({hasText:'Transport for collections'})).toContainText('150.00');
});
