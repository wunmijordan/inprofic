const {test,expect}=require('@playwright/test');
test.skip(process.env.INPROFIC_UI_RELEASE_FIXTURE!=='1','Requires the isolated market stock fixture.');
test('sell directly from Market Stock with compact mobile summary',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('inprofic:essential-privacy-notice:v1','dismissed'));
 await page.goto('/accounts/login/ui-fixture/admin/');
 await page.goto('/inventory/market-stock/');
 await page.getByRole('link',{name:'Sell in Physical Store',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Products sold',exact:true})).toBeVisible();
 const row=page.locator('[data-market-release-row]').first();
 const good=row.locator('select');
 const goodId=await good.locator('option').evaluateAll(options=>options.find(o=>o.textContent==='Fixture Loaf').value);
 await good.selectOption(goodId,{force:true});
 await row.locator('input[name$="-quantity"]').fill('2');
 await expect(row.locator('[data-release-stock-summary]')).toContainText('sold in Physical Store');
 const account=page.locator('select[name="account"]');
 const accountId=await account.locator('option').evaluateAll(options=>options.find(o=>o.value).value);
 await account.selectOption(accountId,{force:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.getByRole('button',{name:'Record Physical Store sale',exact:true}).click();
 await expect(page).toHaveURL(/\/inventory\/market-stock\/$/);
 await expect(page.locator('#distribution-summary').getByRole('columnheader',{name:'Store sales',exact:true})).toBeVisible();
 const text=await page.locator('#distribution-share').evaluate(el=>JSON.parse(el.textContent));
 expect(text).toContain('Sold in Physical Store: 2 loaves');
 expect(text).not.toContain('Reading this report');
 const cards=page.locator('[aria-labelledby="distribution-settlement-heading"] dl > div');
 expect(await cards.count()).toBeGreaterThan(0);
 expect(await cards.evaluateAll(nodes=>nodes.every(node=>{
   const style=getComputedStyle(node);
   return node.classList.contains('workspace-card-raised') && style.boxShadow!=='none' && parseFloat(style.borderRadius)>0;
 }))).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await expect(page.locator('details').filter({has:page.locator('summary').filter({hasText:'Batch lots'})})).not.toHaveAttribute('open','');
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Share distribution summary',exact:true}).click();
 await page.getByRole('menuitem',{name:'Save image',exact:true}).click();
 await (await download).saveAs('/tmp/inprofic-market-physical-sale.png');
});

test('product search exposes current channel prices and recorded applied prices',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('inprofic:essential-privacy-notice:v1','dismissed'));
 await page.goto('/accounts/login/ui-fixture/admin/');
 await page.goto('/dashboard/');
 const search=page.locator('[data-dashboard-search]');
 await search.locator('input[type="search"]').fill('Fixture Loaf');
 await search.locator('.dashboard-search-result').filter({hasText:'Fixture Loaf'}).first().click();
 const dialog=page.locator('.ui-form-dialog');
 await expect(dialog).toBeVisible();
 const frame=page.frameLocator('iframe[name="inprofic-form-dialog"]');
 await expect(frame.locator('#product-prices')).toContainText('Current selling prices');
 await expect(frame.locator('#product-prices')).toContainText('Distribution');
 await frame.getByRole('navigation',{name:'Product sections'}).getByRole('link',{name:'Sales',exact:true}).click();
 await expect(frame.getByRole('columnheader',{name:'Quantity / price',exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await dialog.evaluate(el=>el.getBoundingClientRect().width<=innerWidth+1)).toBe(true);
});
