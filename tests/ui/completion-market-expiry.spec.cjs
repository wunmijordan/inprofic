const {test,expect}=require('@playwright/test');
test.skip(process.env.INPROFIC_UI_COMPLETION_FIXTURE!=='1' || process.env.INPROFIC_UI_RELEASE_FIXTURE!=='1','Requires isolated completion and release fixtures.');
test.beforeEach(async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('inprofic:essential-privacy-notice:v1','dismissed'));
 await page.goto('/accounts/login/ui-fixture/admin/');
});
test('completion cards alternate, preserve inputs and reveal invalid fields',async({page})=>{
 await page.goto('/orders/1/complete/');
 const eventDate=page.locator('input[name="event_date"]');
 await expect(eventDate).toHaveValue('');
 await expect(eventDate).toHaveAttribute('required','');
 await eventDate.fill(await eventDate.getAttribute('max'));
 const cards=page.locator('details[data-completion-card]');
 await expect(cards).toHaveCount(2);
 await expect(cards.nth(0)).toHaveAttribute('open','');
 await expect(cards.nth(1)).not.toHaveAttribute('open','');
 await cards.nth(0).locator('input[name$="-expiry_date"]').fill('2030-01-01');
 await cards.nth(1).locator('summary').click();
 await expect(cards.nth(0)).not.toHaveAttribute('open','');
 await expect(cards.nth(1)).toHaveAttribute('open','');
 await cards.nth(1).locator('input[name$="-produced_units"]').fill('-1');
 await cards.nth(0).locator('summary').click();
 await expect(cards.nth(0).locator('input[name$="-expiry_date"]')).toHaveValue('2030-01-01');
 await page.getByRole('button',{name:'Complete Production',exact:true}).click();
 await expect(cards.nth(1)).toHaveAttribute('open','');
 await cards.nth(0).locator('summary').click();
 await cards.nth(0).locator('input[name$="-produced_units"]').fill('-1');
 await cards.nth(1).locator('summary').click();
 await page.getByRole('button',{name:'Complete Production',exact:true}).click();
 await expect(cards.nth(0)).toHaveAttribute('open','');
 await expect(cards.nth(1)).not.toHaveAttribute('open','');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
test('release combines soon-expiring and no-expiry batches beyond either batch limit',async({page})=>{
 await page.goto('/inventory/market-stock/release/');
 const product=page.locator('select[name="items-0-finished_good"]');
 const value=await product.locator('option').evaluateAll(options=>options.find(o=>o.textContent==='Fixture Loaf').value);
 await product.selectOption(value,{force:true});
 await page.locator('input[name="items-0-quantity"]').fill('64');
 await expect(page.locator('[data-release-stock-summary]')).toContainText('66 loaves');
 await expect(page.locator('[data-release-stock-summary]')).toContainText('2 loaves will remain');
 const dateField=page.locator('input[name="date"]');
 const today=await dateField.inputValue();
 const previous=new Date(`${today}T12:00:00Z`);
 previous.setUTCDate(previous.getUTCDate()-1);
 const yesterday=previous.toISOString().slice(0,10);
 await dateField.fill(yesterday);await dateField.dispatchEvent('change');
 await expect(page.locator('[data-stock-date-status]')).toContainText(`Stock availability as of ${yesterday}`);
 await expect(product.locator('option:checked')).toContainText('unavailable');
 await dateField.fill(today);await dateField.dispatchEvent('change');
 await expect(page.locator('[data-stock-date-status]')).toContainText(`Stock availability as of ${today}`);
 await expect(page.locator('[data-release-stock-summary]')).toContainText('2 loaves will remain');
 const customer=page.locator('select[name="customer"]');
 const customerValue=await customer.locator('option').evaluateAll(options=>options.find(o=>o.textContent==='Customer 00').value);
 await customer.selectOption(customerValue,{force:true});
 await page.getByRole('button',{name:'Release to customer',exact:true}).click();
 await expect(page).toHaveURL(/\/inventory\/market-stock\/$/);
 await expect(page.getByText(/Market Stock released to Customer 00 as Distribution Sale/)).toBeVisible();
});
