const {test, expect} = require('@playwright/test');
test.beforeEach(async ({page}) => {
  await page.addInitScript(() => localStorage.setItem('inprofic:essential-privacy-notice:v1','dismissed'));
  await page.goto('/accounts/login/ui-fixture/admin/');
});

test('multi-vendor request edits, previews, approves and receives one vendor at a time', async ({page}) => {
  await page.goto('/procurement/add/');
  const product = await page.locator('select[name="items-0-item"] option').evaluateAll(options => options.find(o => o.textContent.includes('Fixture Flour')).value);
  await page.locator('select[name="items-0-item"]').selectOption(product, {force:true});
  await page.locator('[name="items-0-supplier"]').fill('UI Vendor Alpha');
  await page.locator('[name="items-0-qty"]').fill('2');
  await page.locator('[name="items-0-unit_cost"]').fill('200');
  await page.getByRole('button',{name:'+ Add Item',exact:true}).click();
  await page.locator('select[name="items-1-item"]').selectOption(product, {force:true});
  await page.locator('[name="items-1-supplier"]').fill('UI Vendor Beta');
  await page.locator('[name="items-1-qty"]').fill('1');
  await page.locator('[name="items-1-unit_cost"]').fill('100');
  await page.getByRole('button',{name:'Submit request',exact:true}).click();
  await expect(page.getByRole('link',{name:'Share request',exact:true})).toHaveCount(1);
  await page.getByRole('link',{name:'Edit request',exact:true}).click();
  const frame = page.frameLocator('iframe[name="inprofic-form-dialog"]');
  await expect(frame.locator('[name="items-1-supplier"]')).toHaveValue('UI Vendor Beta');
  await page.screenshot({path:'/tmp/inprofic-session-captures/multi-vendor-edit.png',fullPage:true});
  await frame.getByRole('button',{name:'Submit request',exact:true}).click();
  await expect(page.locator('.ui-form-dialog')).not.toBeVisible();
  await page.getByRole('link',{name:'Share request',exact:true}).click();
  await expect(frame.locator('[data-request-preview]')).toContainText('UI Vendor Alpha');
  await expect(frame.locator('[data-request-preview]')).toContainText('UI Vendor Beta');
  await page.locator('.ui-form-dialog').getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('link',{name:'Review request',exact:true}).click();
  await expect(frame.locator('.pa-row')).toHaveCount(2);
  await frame.getByRole('button',{name:'Approve request',exact:true}).click();
  await expect(page.locator('.ui-form-dialog')).not.toBeVisible();
  await page.getByRole('button',{name:'Receive',exact:true}).click();
  const receive = page.locator('.ui-legacy-dialog');
  await receive.locator('section').filter({has:page.getByRole('heading',{name:'UI Vendor Alpha',exact:true})}).getByRole('button',{name:'Receive vendor items',exact:true}).click();
  await expect(receive).not.toBeVisible();
  await page.getByRole('button',{name:'Receive',exact:true}).click();
  await expect(receive.locator('section').filter({has:page.getByRole('heading',{name:'UI Vendor Beta',exact:true})}).getByRole('button',{name:'Receive vendor items',exact:true})).toBeVisible();
});

test('distribution snapshot groups customers and split receipts retain a later balance', async ({page}) => {
  await page.goto('/inventory/market-stock/');
  await expect(page.locator('#distribution-summary')).toContainText('Customer 00');
  await expect(page.locator('#distribution-summary')).toContainText('Customer 01');
  const link = page.getByRole('link',{name:'Record payment',exact:true}).first();
  await page.getByText('Review by customer and invoice',{exact:true}).click();
  const paymentURL = await link.getAttribute('href');
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'Share distribution summary',exact:true}).click();
  await page.getByRole('menuitem',{name:'Save image',exact:true}).click();
  await (await download).saveAs('/tmp/inprofic-session-captures/distribution-concise.png');
  await page.goto(paymentURL);
  const chosenCustomer = await page.locator('[name="customer"]').inputValue();
  await expect(page.locator('[data-payment-part]')).toHaveCount(3);
  await page.locator('[name="payments-0-amount"]').fill('500');
  await page.locator('[name="payments-2-amount"]').fill('500');
  const account = await page.locator('[name="payments-0-account"] option').evaluateAll(options => options.find(o => o.textContent.includes('Fixture Till')).value);
  await page.locator('[name="payments-0-account"]').selectOption(account,{force:true});
  await page.locator('[name="payments-2-account"]').selectOption(account,{force:true});
  await expect(page.locator('[data-payment-total]')).toHaveText('1,000.00');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path:'/tmp/inprofic-session-captures/split-customer-payment-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Record payment',exact:true}).click();
  await expect(page).toHaveURL(/\/finance\//);
  await page.goto(paymentURL);
  await expect(page.locator('[name="customer"]')).toHaveValue(chosenCustomer);
  await expect(page.locator('[name="sale"] option:checked')).toContainText('outstanding');
  await expect(page.locator('[name="sale"] option:checked')).not.toContainText('outstanding 0.00');
});
